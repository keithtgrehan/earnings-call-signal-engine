#!/usr/bin/env python3
from __future__ import annotations

import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
TOOLS = ROOT / "tools"
SRC = ROOT / "src"
for path in (TOOLS, SRC):
    if str(path) not in sys.path:
        sys.path.insert(0, str(path))

from experiment_common import (  # noqa: E402
    BENCHMARK_REPORT_PATH,
    GOLD_PATH,
    LABELS,
    READINESS_PATH,
    label_counts,
    load_nlp_registry,
    precision_recall_f1,
    read_jsonl,
    row_label,
    row_text,
    valid_gold_rows,
    write_json,
    write_label_coverage,
    write_next_best_actions,
)
from signal_engine.signal_baseline import predict_deterministic_signal_family  # noqa: E402

GOLD_THRESHOLD = 20
ML_THRESHOLD = 50
EMBEDDING_THRESHOLD = 100


def readiness_payload(rows: list[dict[str, object]]) -> dict[str, object]:
    counts = label_counts(rows)
    missing = [label for label in LABELS if counts.get(label, 0) == 0]
    gold_count = len(rows)
    return {
        "gold_labels": gold_count,
        "valid_gold_rows_with_text": len(valid_gold_rows(rows)),
        "label_counts": {label: counts.get(label, 0) for label in LABELS},
        "missing_labels": missing,
        "evaluation_gate": "insufficient_data" if gold_count < GOLD_THRESHOLD else "deterministic_metrics_allowed",
        "metrics_allowed": gold_count >= GOLD_THRESHOLD,
        "training_gate": "skip_training" if gold_count < ML_THRESHOLD else "local_ml_allowed",
        "training_allowed": gold_count >= ML_THRESHOLD,
        "embeddings_allowed": gold_count >= EMBEDDING_THRESHOLD,
        "dataset_benchmarks_allowed": False,
        "benchmark_claims_allowed": gold_count >= GOLD_THRESHOLD and not missing,
        "canonical_truth": "deterministic_system",
        "enforcement": {
            "no_synthetic_labels": True,
            "no_weak_label_auto_promotion": True,
            "no_metrics_without_valid_gold": True,
            "no_statistical_claims": True,
            "no_silent_dataset_usage": True,
            "embeddings_cannot_override_deterministic_outputs": True,
        },
    }


def run_step(script: str, *args: str, allow_failure: bool = False) -> subprocess.CompletedProcess[str]:
    result = subprocess.run([sys.executable, str(TOOLS / script), *args], cwd=ROOT, text=True, capture_output=True)
    if result.stdout.strip():
        print(result.stdout.strip())
    if result.stderr.strip():
        print(result.stderr.strip(), file=sys.stderr)
    if result.returncode and not allow_failure:
        raise SystemExit(result.returncode)
    return result


def write_status(message: str, payload: dict[str, object]) -> None:
    path = ROOT / "reports" / "evaluation_status.md"
    path.parent.mkdir(parents=True, exist_ok=True)
    lines = ["# Evaluation Status", "", message, "", "```json", json.dumps(payload, indent=2), "```"]
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def write_benchmark_report(rows: list[dict[str, object]], payload: dict[str, object]) -> None:
    counts = label_counts(rows)
    metrics = payload.get("metrics") or {}
    examples = payload.get("examples") or {"correct": [], "failures": []}
    local_ml_report = ROOT / "reports" / "experiment_results" / "local_ml_baseline.md"
    lines = [
        "# First 50 Benchmark Report",
        "",
        "This report is generated by `tools/run_evaluation_loop.py`. It does not make statistical or production claims.",
        "",
        "## Dataset Size",
        "",
        f"- gold_labels: `{len(rows)}`",
        f"- valid_gold_rows_with_text: `{len(valid_gold_rows(rows))}`",
        "",
        "## Label Distribution",
        "",
        *[f"- `{label}`: {counts.get(label, 0)}" for label in LABELS],
        "",
        "## Deterministic Metrics",
        "",
    ]
    if metrics:
        lines.extend(["```json", json.dumps(metrics, indent=2), "```"])
    else:
        lines.append("Insufficient gold labels for evaluation.")
    lines.extend(
        [
            "",
            "## Metric Interpretation",
            "",
            "The current deterministic baseline has higher recall than precision. In practical terms, the system is currently better at finding candidate signals than at avoiding false positives, so the next useful improvement target is precision.",
            "",
            "This is a measurable baseline, not product proof. The numbers are useful for tracking whether deterministic rule changes make the system better or worse against the current gold set.",
            "",
            "## Known Caveats",
            "",
            "- Imported labels have mixed provenance.",
            "- Some guidance labels were mapped conservatively into the four-label Signal Engine taxonomy.",
            "- `data/labeling/reviewed_labels.csv` still has no accepted review decisions.",
            "- The benchmark remains small and should not be treated as statistically significant.",
            "",
            "## Next Improvement Target",
            "",
            "Improve precision by reducing false positives while preserving the useful recall on `risk_friction` and `opportunity_commitment`.",
            "",
            "## ML Baseline Comparison",
            "",
        ]
    )
    if local_ml_report.exists():
        lines.extend(
            [
                "- `tools/run_next_experiment.py` selected `local_ml_baseline` because the gold set has enough valid labels.",
                "- Result artifact: `reports/experiment_results/local_ml_baseline.md`",
                "- Status: see the experiment artifact for the latest smoke-fit result.",
                "- This is a benchmark-only smoke fit; no model artifact is committed and it does not override deterministic outputs.",
            ]
        )
    else:
        lines.append("Not run unless `tools/run_next_experiment.py` selects a gated local ML experiment with >=50 gold labels.")
    lines.extend(
        [
            "",
            "## Embedding Insights",
            "",
            "Not run unless `tools/run_embedding_benchmark.py --enable-retrieval-experiment` is used or >=100 gold labels exist.",
            "",
            "## Error Patterns",
            "",
        ]
    )
    for error in payload.get("error_patterns", []):
        lines.append(f"- {error}")
    if not payload.get("error_patterns"):
        lines.append("- No error analysis available because metrics were skipped or no valid rows exist.")
    lines.extend(["", "## Examples", "", "### Correct", ""])
    for item in examples.get("correct", [])[:3]:
        lines.append(f"- `{item.get('id', '')}` {item.get('label', '')}: {item.get('text', '')[:160]}")
    if not examples.get("correct"):
        lines.append("- None available.")
    lines.extend(["", "### Failures", ""])
    for item in examples.get("failures", [])[:3]:
        lines.append(f"- `{item.get('id', '')}` true={item.get('label', '')} pred={item.get('prediction', '')}: {item.get('text', '')[:160]}")
    if not examples.get("failures"):
        lines.append("- None available.")
    lines.extend(
        [
            "",
            "## What this does NOT prove",
            "",
            "- No statistical significance.",
            "- No production ML validity.",
            "- No market prediction.",
            "- No embedding or dataset benchmark superiority.",
            "- No retrieval quality claim.",
            "- No long-context benchmark claim.",
            "- No override of deterministic canonical outputs.",
        ]
    )
    BENCHMARK_REPORT_PATH.parent.mkdir(parents=True, exist_ok=True)
    BENCHMARK_REPORT_PATH.write_text("\n".join(lines) + "\n", encoding="utf-8")


def evaluate_rows(rows: list[dict[str, object]]) -> dict[str, object]:
    valid_rows = valid_gold_rows(rows)
    y_true: list[str] = []
    y_pred: list[str] = []
    examples = {"correct": [], "failures": []}
    for row in valid_rows:
        label = row_label(row)
        prediction = str(predict_deterministic_signal_family(row_text(row)).get("label"))
        y_true.append(label)
        y_pred.append(prediction)
        bucket = "correct" if label == prediction else "failures"
        examples[bucket].append(
            {
                "id": row.get("id") or row.get("candidate_id") or "",
                "label": label,
                "prediction": prediction,
                "text": row_text(row),
            }
        )
    metrics = precision_recall_f1(y_true, y_pred)
    error_counts = {}
    for truth, pred in zip(y_true, y_pred, strict=False):
        if truth != pred:
            key = f"{truth} -> {pred}"
            error_counts[key] = error_counts.get(key, 0) + 1
    return {
        "metrics_computed": True,
        "metrics": metrics,
        "examples": examples,
        "error_patterns": [f"{key}: {count}" for key, count in sorted(error_counts.items())],
    }


def main() -> int:
    validation = run_step("validate_reviewed_batch.py", allow_failure=True)
    if validation.returncode == 0:
        update = run_step("update_gold_from_review.py", allow_failure=True)
        if update.returncode != 0:
            print("Reviewed-batch promotion was not applied; continuing with existing canonical gold labels.")
    else:
        print(
            "No accepted reviewed-batch rows found; continuing with existing canonical gold labels. "
            "See docs/labeling/review_validation_report.md for validation details."
        )
    rows = read_jsonl(GOLD_PATH)
    write_label_coverage(rows)
    payload: dict[str, object] = {
        **readiness_payload(rows),
        "threshold": GOLD_THRESHOLD,
        "metrics_computed": False,
        "message": "",
    }
    if len(rows) < GOLD_THRESHOLD:
        payload["message"] = "Insufficient gold labels for evaluation"
        write_status("Insufficient gold labels for evaluation", payload)
    else:
        payload.update(evaluate_rows(rows))
        write_json(READINESS_PATH, payload)
        write_status("Evaluation completed with deterministic baseline metrics.", payload)
    if not READINESS_PATH.exists() or len(rows) < GOLD_THRESHOLD:
        write_json(READINESS_PATH, payload)
    write_benchmark_report(rows, payload)
    write_next_best_actions(gold_count=len(rows), readiness=payload, registry=load_nlp_registry())
    print(json.dumps(payload, indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
